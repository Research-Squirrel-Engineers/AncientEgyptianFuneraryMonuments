def esc(s) -> str:
    return html.escape(str(s), quote=True)


def _doc_url(file: str) -> str:
    return "/" if file == "index.html" else "/" + file


def nav_static(active: str) -> str:
    """Navigation of a page in docs/visuals/. `active` is the file of the current page in visuals/."""
    def doc(p, t):
        return f'<a href="../{p}">{esc(t)}</a>'

    def vis(p, t):
        on = ' class="on"' if p == active else ""
        return f'<a{on} href="{p}">{esc(t)}</a>'

    return ("<nav>"
            '<div class="grp"><span class="lab">Documentation</span><span class="lnk">' + "".join(doc(p, t) for p, t in DOC_PAGES) + "</span></div>"
            '<div class="grp"><span class="lab">Visuals</span><span class="lnk">' + "".join(vis(p, t) for p, t in VISUAL_PAGES) + "</span></div>"
            "</nav>")


def nav_liquid() -> str:
    """The same navigation for the Jekyll layout; the active page is decided by page.url."""
    def doc(p, t):
        u = _doc_url(p)
        return f'<a{{% if page.url == "{u}" %}} class="on"{{% endif %}} href="{{{{ \'{u}\' | relative_url }}}}">{esc(t)}</a>'

    def vis(p, t):
        path = "/visuals/" + ("" if p == "index.html" else p)
        return f'<a href="{{{{ \'{path}\' | relative_url }}}}">{esc(t)}</a>'

    return ("<nav>"
            '<div class="grp"><span class="lab">Documentation</span><span class="lnk">' + "".join(doc(p, t) for p, t in DOC_PAGES) + "</span></div>"
            '<div class="grp"><span class="lab">Visuals</span><span class="lnk">' + "".join(vis(p, t) for p, t in VISUAL_PAGES) + "</span></div>"
            "</nav>")


def layout() -> str:
    return ("<!DOCTYPE html>\n<html lang=\"en-GB\">\n<head>\n<meta charset=\"utf-8\">\n"
            "<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n"
            "<title>{{ page.title }} · " + SITE_TITLE + "</title>\n"
            "<link rel=\"stylesheet\" href=\"{{ '/assets/site.css' | relative_url }}\">\n</head>\n<body>\n<main>\n"
            + nav_liquid() + "\n<h1>{{ page.title }}</h1>\n{% if page.intro %}<p class=\"intro\">{{ page.intro }}</p>{% endif %}\n"
            "<article class=\"prose\">\n{{ content }}\n</article>\n</main>\n" + JS_COPY + "\n</body></html>\n")


def config() -> str:
    return (f"title: {SITE_TITLE}\nbaseurl: {BASEURL}\nmarkdown: kramdown\nkramdown:\n  input: GFM\n  hard_wrap: false\n"
            "exclude:\n  - README.md\n")


def page_static(file: str, title: str, intro: str, body: str) -> str:
    """A complete static page in docs/visuals/. `intro` and `body` are HTML, `title` is plain text."""
    return ("<!DOCTYPE html>\n<html lang=\"en-GB\">\n<head>\n<meta charset=\"utf-8\">\n"
            "<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n"
            f"<title>{esc(title)} · {SITE_TITLE}</title>\n<link rel=\"stylesheet\" href=\"../assets/site.css\">\n</head>\n<body>\n<main>\n"
            f"{nav_static(file)}\n<h1>{esc(title)}</h1>\n<p class=\"intro\">{intro}</p>\n{body}\n</main>\n{JS_COPY}\n</body></html>\n")


def write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def write_assets() -> None:
    """docs/assets/site.css, docs/assets/fonts/, docs/_layouts/default.html, docs/_config.yml."""
    (DOCS / "assets" / "fonts").mkdir(parents=True, exist_ok=True)
    write_text(DOCS / "assets" / "site.css", CSS)
    for f in sorted(FONTS.glob("FiraSans-*.ttf")):
        shutil.copyfile(f, DOCS / "assets" / "fonts" / f.name)
    write_text(DOCS / "_layouts" / "default.html", layout())
    write_text(DOCS / "_config.yml", config())


def png_size(path: Path) -> tuple[int, int]:
    with open(path, "rb") as fh:
        head = fh.read(24)
    return struct.unpack(">II", head[16:24])


def fig_card(imgdir: Path, name: str, label: str, caption: str, credit: str, href_dir: str = "img") -> str:
    """Figure card: PNG in the page (an SVG used as <img> cannot load the page's fonts), SVG as a download."""
    w, h = png_size(imgdir / f"{name}.png")
    return (f'<section>\n<img src="{href_dir}/{name}.png" width="{w}" height="{h}" loading="lazy" alt="{esc(caption)}">\n'
            f'<div class="row"><p class="cap"><span class="n">{esc(label)}</span>{esc(caption)}</p>'
            f'<button type="button" data-c="{esc(caption)}">Copy</button></div>\n'
            f'<p class="cr">{esc(credit)}</p>\n'
            f'<p class="dl"><a href="{href_dir}/{name}.png" download>PNG</a><a href="{href_dir}/{name}.svg" download>SVG</a></p>\n</section>')
